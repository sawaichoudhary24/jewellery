CREATE DATABASE IF NOT EXISTS jewellery_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE jewellery_db;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL, phone VARCHAR(30) DEFAULT NULL, address TEXT, city VARCHAR(100),
 state VARCHAR(100), pincode VARCHAR(20), role ENUM('user','admin') NOT NULL DEFAULT 'user',
 status ENUM('active','inactive') NOT NULL DEFAULT 'active', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS categories (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE, slug VARCHAR(150) NOT NULL UNIQUE,
 description TEXT, status ENUM('active','inactive') NOT NULL DEFAULT 'active', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS products (
 id INT AUTO_INCREMENT PRIMARY KEY, category_id INT NULL, name VARCHAR(200) NOT NULL, slug VARCHAR(220) NOT NULL UNIQUE,
 sku VARCHAR(100), description TEXT, short_description TEXT, price DECIMAL(12,2) NOT NULL DEFAULT 0,
 sale_price DECIMAL(12,2) NULL, stock INT NOT NULL DEFAULT 0, image VARCHAR(255), image2 VARCHAR(255),
 image3 VARCHAR(255), image4 VARCHAR(255), material VARCHAR(100), weight VARCHAR(100), size VARCHAR(100),
 status ENUM('active','inactive') NOT NULL DEFAULT 'active', featured TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(category_id) REFERENCES categories(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS cart (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, product_id INT NOT NULL, quantity INT NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY uq_cart(user_id,product_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS orders (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, order_number VARCHAR(50) NOT NULL UNIQUE,
 name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL, phone VARCHAR(30), address TEXT, city VARCHAR(100),
 state VARCHAR(100), pincode VARCHAR(20), subtotal DECIMAL(12,2) NOT NULL DEFAULT 0, shipping DECIMAL(12,2) NOT NULL DEFAULT 0,
 total DECIMAL(12,2) NOT NULL DEFAULT 0, payment_method VARCHAR(50) NOT NULL DEFAULT 'COD',
 payment_status VARCHAR(50) NOT NULL DEFAULT 'pending', order_status VARCHAR(50) NOT NULL DEFAULT 'pending',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS order_items (
 id INT AUTO_INCREMENT PRIMARY KEY, order_id INT NOT NULL, product_id INT NULL, product_name VARCHAR(200) NOT NULL,
 quantity INT NOT NULL, price DECIMAL(12,2) NOT NULL, total DECIMAL(12,2) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE, FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS messages (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL, phone VARCHAR(30),
 subject VARCHAR(200), message TEXT NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'unread', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
